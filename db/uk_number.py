"""Числа українськими словами для друкованих форм.

Інвентаризаційний опис за наказом Мінфіну від 17.06.2015 №572 вимагає п'ять
підсумків прописом. Формат узято не з підручника, а з описів, які служба вже
здавала: розряди скорочуються («дві тис. триста сорок п'ять грн. 60 коп.»), а не
пишуться словом «тисяч». Через це рід у назві розряду не видно — але він
потрібен усередині: «двадцять одна тис.», не «один».

Кількість буває дробовою (21,250 кг), тому тисячні пишуться цифрами:
«двадцять одна ціла 250 тисячних». Вигадувати для них слова немає підстав —
у бланку такого запису немає, а число має лишитися впізнаваним.
"""

ONES = {
    "m": ["", "один", "два", "три", "чотири", "п'ять", "шість", "сім", "вісім",
          "дев'ять"],
    "f": ["", "одна", "дві", "три", "чотири", "п'ять", "шість", "сім", "вісім",
          "дев'ять"],
}
TEENS = ["десять", "одинадцять", "дванадцять", "тринадцять", "чотирнадцять",
         "п'ятнадцять", "шістнадцять", "сімнадцять", "вісімнадцять", "дев'ятнадцять"]
TENS = ["", "", "двадцять", "тридцять", "сорок", "п'ятдесят", "шістдесят",
        "сімдесят", "вісімдесят", "дев'яносто"]
HUNDREDS = ["", "сто", "двісті", "триста", "чотириста", "п'ятсот", "шістсот",
            "сімсот", "вісімсот", "дев'ятсот"]

# Розряд: скорочення й рід числівника перед ним. Тисяча — жіночого роду,
# мільйон і мільярд — чоловічого.
SCALES = [(10 ** 9, "млрд.", "m"), (10 ** 6, "млн.", "m"), (10 ** 3, "тис.", "f")]


def _under_thousand(n: int, gender: str) -> str:
    parts = []
    if n >= 100:
        parts.append(HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        parts.append(TEENS[n - 10])
    else:
        if n >= 20:
            parts.append(TENS[n // 10])
            n %= 10
        if n:
            parts.append(ONES[gender][n])
    return " ".join(parts)


def number_words(n: int, gender: str = "m") -> str:
    """Ціле число словами; розряди — скороченнями, як у бланку."""
    if n == 0:
        return "нуль"
    parts = []
    for value, label, scale_gender in SCALES:
        if n >= value:
            head, n = divmod(n, value)
            parts.append(_under_thousand(head, scale_gender))
            parts.append(label)
    if n:
        parts.append(_under_thousand(n, gender))
    return " ".join(p for p in parts if p)


def _cap(s: str) -> str:
    return s[:1].upper() + s[1:]


def money_words(kop: int) -> str:
    """«Дві тис. триста сорок п'ять грн. 60 коп.»

    Копійки — цифрами з двох знаків: так у бланку, і так їх не сплутати.
    """
    grn, rest = divmod(int(kop), 100)
    return f"{_cap(number_words(grn, 'f'))} грн. {rest:02d} коп."


def qty_words(qty_milli: int) -> str:
    """«Тридцять сім» або «Двадцять одна ціла 250 тисячних»."""
    whole, milli = divmod(int(qty_milli), 1000)
    text = _cap(number_words(whole, "f"))
    return text if not milli else f"{text} ціла {milli} тисячних"
