-- Вид обліку позиції — необоротний актив чи запаси — за ФЕС.
--
-- Що вважати необоротним активом, вирішує фінансовий орган: він ставить
-- позицію на субрахунок 10xx/11xx (основні засоби, інші необоротні матеріальні
-- активи) і дає їй інвентарний номер — або веде як запаси (15xx/18xx) під
-- номенклатурним номером. У `fes_code` перше — інвентарний номер із десяти
-- цифр, що починається з класу рахунку 10 чи 11; друге — номенклатурний номер
-- іншої довжини. Ознака, успадкована з «Облік ТЗ 3.0», розходилася з ФЕС в
-- обидва боки. Позиції без коду ФЕС лишаються як є: їхній вид обліку
-- підтверджує людина в картці позиції.
--
-- Це правило, а не зміна схеми: перенос із 3.0 (build/migrate_to_db.py) і чиста
-- база дистрибутива (build/make_distro.py) виконують його після наповнення, а
-- після оновлення кодів ФЕС його запускають ще раз.
UPDATE nomen
   SET is_fixed_asset = CASE WHEN length(fes_code) = 10 AND substr(fes_code, 1, 2) IN ('10', '11')
                             THEN 1 ELSE 0 END
 WHERE fes_code IS NOT NULL AND fes_code <> ''
   AND is_fixed_asset <> CASE WHEN length(fes_code) = 10 AND substr(fes_code, 1, 2) IN ('10', '11')
                              THEN 1 ELSE 0 END;
