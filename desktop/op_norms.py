def per_milli(per_ration):
    """Норма на д/д у тисячних одиниці позиції, точно (0.0016 кг → 1.6); порожня чи нульова — None."""
    if per_ration in (None, ""):
        return None
    value = Decimal(str(round(float(per_ration), 6))) * 1000
    return value if value > 0 else None


def line_key(text):
    """Рядок норми з того, що прийшло (ключ PER_RATION чи назва рядка, без різниці регістру й зайвих пробілів) → ключ;
    порожньо — None; невідоме — ValueError."""
    t = " ".join(str(text or "").split())
    if not t:
        return None
    if t in LINES:
        return t
    hit = next((n["key"] for n in PER_RATION if n["name"].lower() == t.lower()), None)
    if hit is None:
        raise ValueError(t)
    return hit


def line_state(group, uom, per, line=None):
    """Що каже про рядок норми наказу 390 позиція ОП: ("line", ключ) — рядок вибрано в картці (`line` — ключ PER_RATION)
    чи група, одиниця й норма на д/д (`per` — у тисячних, як per_milli) відповідають одному рядку (набір — 1 к-т, серветки —
    3 шт); ("own", None) — число не з наказу (своя норма служби); ("ambiguous", [ключі]) — число є в кількох рядках, а рядка
    не вибрано: тарілка мілка й виделка — обидві по 3 шт, рідкий і порошковий миючий — по 0,0016 кг."""
    if line in LINES:
        return "line", line
    hits = [n["key"] for n in PER_RATION if n["group"] == group and n["uom"] == uom and Decimal(n["per"]) * 1000 == per]
    if len(hits) == 1:
        return "line", hits[0]
    return ("ambiguous", hits) if hits else ("own", None)


def line_of(group, uom, per, line=None):
    """Рядок норми позиції (line_state), коли його можна сказати; інакше None."""
    state, key = line_state(group, uom, per, line)
    return key if state == "line" else None


def pool_key(group, uom, per, line, name):
    """Пул акта — позиції, що ділять одну межу «д/д × норма». Один рядок норми наказу — один пул, хоч би кодів (ціна
    інша — код інший) і назв у ньому було кілька; своя норма служби (числа немає в наказі) — свій пул виробу (назви);
    число є в кількох рядках, а рядка не вибрано, — None: такої позиції в акті немає (R60), бо пул за назвою дав би
    кожному виробу всю норму рядка. Норма (`per`, тисячні) — теж у ключі: межа пулу рахується однією нормою."""
    state, key = line_state(group, uom, per, line)
    if state == "ambiguous":
        return None
    return (group, ("line", key) if state == "line" else ("item", " ".join(str(name or "").lower().split())), per)


def pool_keys(items):
    """Пули для переліку позицій ({group, uom, per, line, name}) — як pool_key, але код без вибраного рядка з неоднозначним
    числом бере рядок іншого коду того самого виробу (та сама група, норма й назва), де рядок вибрано: інша ціна — інший
    код, а межа — та сама, спільна. Без такого коду — None (позиції в акті немає)."""
    fold = lambda s: " ".join(str(s or "").lower().split())                             # noqa: E731
    named = {}
    for it in items:
        line = line_of(it["group"], it["uom"], it["per"], it.get("line"))
        if line:
            named.setdefault((it["group"], it["per"], fold(it["name"])), line)
    return [pool_key(it["group"], it["uom"], it["per"],
                     line_of(it["group"], it["uom"], it["per"], it.get("line"))
                     or named.get((it["group"], it["per"], fold(it["name"]))), it["name"]) for it in items]


def per_text(per):
    """Норма на д/д (тисячні) словами паперу: 1,6 → «0,0016», 3000 → «3»."""
    value = (Decimal(per) / 1000).normalize()
    return format(value, "f").replace(".", ",")


def pool_order(key):
    """Порядок пулів в акті: група, далі рядки норми — як у наказі, далі вироби без рядка — за назвою."""
    group, (kind, ident), per = key
    return (group, 0, _ORDER[ident], "", per) if kind == "line" else (group, 1, 0, ident, per)


